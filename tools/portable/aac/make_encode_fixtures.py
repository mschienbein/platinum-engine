def write_manifest(path, header, entries):
    with open(path, "w") as f:
        f.write("{\n")
        for k, v in header.items():
            f.write(f' "{k}": {json.dumps(v)},\n')
        f.write(' "items": [\n' + ",\n".join("  " + json.dumps(e, separators=(",", ":")) for e in entries) + "\n ]\n}\n")


