def sha256(data):
    return hashlib.sha256(data).hexdigest()


# ---- the item table --------------------------------------------------------------------------------------------------------

def item(group, id_, kind, rate, channels, frames, params, **extra):
    seed = int.from_bytes(hashlib.sha256(id_.encode()).digest()[:8], "big")
    return dict(id=id_, group=group, kind=kind, rate=rate, channels=channels, frames=frames, seed=seed,
                params=list(params) + [0] * (4 - len(params)), **extra)


def ms(rate, millis):
    return rate * millis // 1000


