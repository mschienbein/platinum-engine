#!/usr/bin/env python3
"""Rebuild (macOS arm64) or check (anywhere) the golden fixtures of tests/portable_aac_encode.rs.

    python3 tools/portable/aac/make_encode_fixtures.py --record --work /tmp/aac-encode-work [--crosscheck CORPUS RUNS]... [--layout DIR]
    python3 tools/portable/aac/make_encode_fixtures.py --append --work /tmp/aac-encode-append
    python3 tools/portable/aac/make_encode_fixtures.py --verify

--record builds tools/portable/aac/encode_probe (the engine's own macOS apple_codec::Writer, AudioToolbox), runs it over the
item table below three times (the third in a process whose environment is padded, which moves the stack), requires the three
recordings to be identical, re-records the write-size items at other write sizes and the flush-to-zero items in the engine's
flush-to-zero scope, records the refusal grid and the misuse cases twice, optionally compares the engine Writer with
independent sets of Apple encodes (--crosscheck CORPUS_DIR RUNS_DIR, --layout DIR; see encode_probe), and only then writes
tests/fixtures/aac-encode/{manifest.json,refusals.json,refs.bin}. WORK must not exist. Nothing is overwritten unless
--overwrite is given. The input of every item is generated by tests/support/aac_encode_input.rs; this table only says which.

--append records only the plain items of the table that the manifest does not list yet (a new item group), on the machine the pack was
recorded on, and adds them to manifest.json and behind the existing references of refs.bin; nothing recorded before is touched.

--verify needs no Apple component: it checks refs.bin against manifest.json (pack hash, every kept reference's hash and its
access units), the invariants the table promises (accepted configurations, lengths, kinds, budget) and refusals.json's shape.
"""
