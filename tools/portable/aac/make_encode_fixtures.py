def verify():
    with open(os.path.join(FIXTURES, "manifest.json")) as f:
        manifest = json.load(f)
    with open(os.path.join(FIXTURES, "refs.bin"), "rb") as f:
        pack = f.read()
    assert manifest["schema"] == SCHEMA
    assert sha256(pack) == manifest["pack"]["sha256"] and len(pack) == manifest["pack"]["bytes"], "refs.bin does not match the manifest"
    table = {i["id"]: i for i in build_items()}
    items = manifest["items"]
    assert [i["id"] for i in items] == sorted(table), "the manifest does not list the item table's ids"
    spans, kept = [], 0
    for e in items:
        want = table[e["id"]]
        for k in ("group", "kind", "rate", "channels", "frames", "seed", "params"):
            assert e[k] == want[k], f"{e['id']}: {k} differs from the item table"
        assert e.get("write_sizes") == want.get("write_sizes")
        frames = e["frames"]
        assert e["au_count"] == (0 if frames == 0 else -(-(frames + 2112) // 1024)), f"{e['id']}: access-unit count"
        if e["group"] != "long":
            assert sum(e["au_sizes"]) > 0 or e["au_count"] == 0
            assert len(e["au_sizes"]) == e["au_count"] == len(e["au_sha8"].split())
        if "ref" in e:
            r = e["ref"]
            assert r["length"] <= REF_ITEM_LIMIT
            spans.append((r["offset"], r["length"]))
            data = restore(pack[r["offset"]:r["offset"] + r["length"]], r["zeros"])
            assert sha256(data) == e["m4a_sha256"] and len(data) == e["m4a_length"], f"{e['id']}: reference file"
            kept += 1
    end = 0
    for offset, length in sorted(spans):
        assert offset == end, "the kept references do not tile refs.bin"
        end += length
    assert end == len(pack) <= REF_TOTAL_LIMIT
    configs = sorted({(i["rate"], i["channels"]) for i in items if i["group"] == "grid"})
    assert configs == sorted(ACCEPTED), "the grid must cover every accepted configuration"
    default = [i for i in items if i["group"] != "long"]
    seconds = sum(i["frames"] / i["rate"] * (1 + len(i.get("write_sizes", [])) + (1 if i["id"] in FZ_ITEMS else 0)) for i in default) + 3.0
    assert seconds <= DEFAULT_SECONDS_LIMIT, f"{seconds:.1f} s of audio in the default tests"
    with open(os.path.join(FIXTURES, "refusals.json")) as f:
        refusals = json.load(f)
    assert len(refusals["cells"]) == len(refusals["rates"]) * len(refusals["channels"])
    print(f"ok: {len(items)} items ({len(default)} default, {kept} with a kept reference), {len(pack)} bytes of references, "
          f"{seconds:.1f} s of audio incl. write sizes, {len(refusals['cells'])} refusal cells")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--record", action="store_true")
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--work", help="a directory that does not exist yet")
    parser.add_argument("--crosscheck", nargs=2, action="append", metavar=("CORPUS_DIR", "RUNS_DIR"))
    parser.add_argument("--layout", metavar="DIR")
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--append", action="store_true")
    args = parser.parse_args()
    if args.record:
        if not args.work:
            parser.error("--record needs --work")
        record(args)
    elif args.append:
        if not args.work:
            parser.error("--append needs --work")
        append(args)
    elif args.verify:
        verify()
    else:
        parser.error("--record, --append or --verify")


if __name__ == "__main__":
    main()
