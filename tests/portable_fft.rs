fn next(state: &mut u64) -> u32 {
    *state ^= *state << 13;
    *state ^= *state >> 7;
    *state ^= *state << 17;
    (*state >> 16) as u32
}

fn input(case: usize, index: usize, imaginary: bool, state: &mut u64) -> f32 {
    match case {
        1 => if !imaginary && index == 0 { 1.0 } else { 0.0 },
        3 => 0.5,
        4 => if imaginary { -0.5 } else { 0.5 },
        6 => f32::from_bits([
            0, 0x8000_0000, 1, 0x8000_0001,
            0x007f_ffff, 0x807f_ffff, 0x0080_0000, 0x8080_0000,
        ][(index + usize::from(imaginary)) % 8]),
        7 => {
            let bits = next(state);
            let exponent = 110 + ((bits >> 23) % 23);
            f32::from_bits((bits & 0x807f_ffff) | (exponent << 23))
        }
        _ => unreachable!(),
    }
}

fn read_control() -> u64 {
    #[cfg(target_arch = "aarch64")]
    { let value: u64; unsafe { std::arch::asm!("mrs {0}, fpcr", out(reg) value, options(nostack, preserves_flags)); } value }
    #[cfg(target_arch = "x86_64")]
    { let mut value = 0u32; unsafe { std::arch::asm!("stmxcsr [{0}]", in(reg) &mut value, options(nostack, preserves_flags)); } value as u64 }
}
fn write_control(value: u64) {
    #[cfg(target_arch = "aarch64")]
    unsafe { std::arch::asm!("msr fpcr, {0}", in(reg) value, options(nostack, preserves_flags)); }
    #[cfg(target_arch = "x86_64")]
    { let value = value as u32; unsafe { std::arch::asm!("ldmxcsr [{0}]", in(reg) &value, options(nostack, preserves_flags)); } }
}
struct Restore(u64);
impl Drop for Restore { fn drop(&mut self) { write_control(self.0); } }

#[test]
fn aligned_reference_words_match_for_supported_sizes_and_modes() {
    let original = read_control();
    let _restore = Restore(original);
    #[cfg(target_arch = "aarch64")] let (mask, fz) = ((1u64 << 24) | (1u64 << 25), 1u64 << 24);
    #[cfg(target_arch = "x86_64")] let (mask, fz) = ((1u64 << 15) | (1u64 << 6), (1u64 << 15) | (1u64 << 6));
    let mut fixture = 0;
    for log2n in 9..=15 {
        let setup = FftSetup::new(log2n);
        let half = 1usize << (log2n - 1);
        let indices = [0, 1, 2, 3, 7, half / 4, half / 2, half - 1];
        for flush in [false, true] {
            write_control((original & !mask) | if flush { fz } else { 0 });
            for inverse in [false, true] {
                for case in CASES {
                    let mut state = 0x243f_6a88_85a3_08d3u64;
                    let mut real = vec![0.0; half];
                    let mut imaginary = vec![0.0; half];
                    for j in 0..half {
                        real[j] = input(case, j, false, &mut state);
                        imaginary[j] = input(case, j, true, &mut state);
                    }
                    if inverse { setup.inverse(&mut real, &mut imaginary); }
                    else { setup.forward(&mut real, &mut imaginary); }
                    let mut actual = [0u32; 16];
                    for (j, index) in indices.into_iter().enumerate() {
                        actual[j] = real[index].to_bits();
                        actual[j + 8] = imaginary[index].to_bits();
                    }
                    assert_eq!(actual, EXPECTED[fixture], "log2n={log2n} flush={flush} inverse={inverse} case={case}");
                    fixture += 1;
                }
            }
        }
    }
    assert_eq!(fixture, EXPECTED.len());
}

#[test]
fn sme_default_nan_matches_reference_for_exceptional_input() {
    for log2n in 9..=15 {
        let setup = FftSetup::new(log2n);
        let half = 1usize << (log2n - 1);
        for bits in [0x7fc1_2345, 0xff81_2345, 0x7f80_0000] {
            for inverse in [false, true] {
                let mut real = vec![0.0; half];
                let mut imaginary = vec![0.0; half];
                real[7] = f32::from_bits(bits);
                if inverse { setup.inverse(&mut real, &mut imaginary); }
                else { setup.forward(&mut real, &mut imaginary); }
                assert!(real.iter().chain(&imaginary).all(|value| value.to_bits() == 0x7fc0_0000),
                    "log2n={log2n} bits={bits:#x} inverse={inverse}");
            }
        }
    }
}
